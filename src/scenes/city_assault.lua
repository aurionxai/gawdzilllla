    _blameText  = nil,
    _fartAlpha  = 0,
    _strutDir   = 1,
  }
  self._announce     = "GREGG HAS ARRIVED. OH NO."
  self._announceTimer = 2.8
end

function CA:_updateGregg(dt)
  local g = self._gregg

  -- Keep Gregg anchored near camera view
  local camL = self._camX + 10
  local camR = self._camX + SCREEN_W - 10

  if g.state == "WANDER" then
    g.x = g.x + g.dir * GREGG_SPEED * dt
    if g.x < camL then g.dir =  1 end
    if g.x > camR then g.dir = -1 end

    -- Seek the nearest uncollected food item in view
    local best, bestD = nil, math.huge
    for _, item in ipairs(self._items) do
      if not item.collected then
        local d = math.abs(item.x - g.x)
        if d < bestD and d < 400 then best = item; bestD = d end
      end
    end
    if best then
      g._targetFood = best
      g.state = "SEEK"
    end

  elseif g.state == "SEEK" then
    if not g._targetFood or g._targetFood.collected then
      g.state = "WANDER"; g._targetFood = nil; return
    end
    local dx = g._targetFood.x - g.x
    g.dir = dx > 0 and 1 or -1
    g.x   = g.x + g.dir * GREGG_SPEED * 1.6 * dt
    -- Eat if overlapping
    local gb = { x=g.x, y=g.y, w=g.w, h=g.h }
    local fb = g._targetFood
    if AS.overlaps(gb, fb) then
      g._targetFood.collected = true
      g._targetFood           = nil
      g.state                 = "EAT"
      g._timer                = 0.9
    end

  elseif g.state == "EAT" then
    g._timer = g._timer - dt
    if g._timer <= 0 then
      g.state      = "FART"
      g._timer     = 1.2
      g._fartAlpha = 1.0
    end

  elseif g.state == "FART" then
    g._timer     = g._timer - dt
    g._fartAlpha = math.max(0, g._timer)
    if g._timer <= 0 then
      local targetName = self._p1.stats.characterName
      local line       = GREGG_BLAME[math.random(#GREGG_BLAME)]
      g._blameText = string.format(line, targetName)
      g._strutDir  = self._ctrl1.x > g.x and -1 or 1
      g._fartAlpha = 0.45
      g.state      = "BLAME"
      g._timer     = 2.2
    end

  elseif g.state == "BLAME" then
    g._timer     = g._timer - dt
    g._fartAlpha = math.max(0, g._timer * 0.18)
    if g._timer <= 0 then
      g.state      = "STRUT"
      g._timer     = 1.5
      g._blameText = nil
      g._fartAlpha = 0
    end

  elseif g.state == "STRUT" then
    g._timer = g._timer - dt
    g.x = g.x + g._strutDir * GREGG_SPEED * 1.8 * dt
    g.x = math.max(camL, math.min(camR, g.x))
    if g._timer <= 0 then
      g.state = "WANDER"
      g.dir   = g._strutDir
    end
  end
end

function CA:_drawGregg()
  local g = self._gregg
  local x, y = math.floor(g.x), math.floor(g.y)

  -- Fart cloud (green, behind him)
  if g._fartAlpha and g._fartAlpha > 0 then
    local cx = g.dir > 0 and (x - 16) or (x + g.w)
    love.graphics.setColor(0.30, 0.78, 0.20, g._fartAlpha * 0.75)
    love.graphics.rectangle("fill", cx,     y + g.h - 20, 20, 14, 4)
    love.graphics.rectangle("fill", cx + 2, y + g.h - 30, 14, 12, 4)
    love.graphics.rectangle("fill", cx + 4, y + g.h - 38, 10, 10, 3)
  end

  -- Body (deep purple)
  love.graphics.setColor(0.28, 0.08, 0.44)
  love.graphics.rectangle("fill", x, y, g.w, g.h)
  -- Belly
  love.graphics.setColor(0.42, 0.12, 0.62)
  love.graphics.rectangle("fill", x + 5, y + 8, g.w - 10, g.h - 14)
  -- Eyebrows (scheming)
  love.graphics.setColor(0.15, 0.04, 0.22)
  love.graphics.rectangle("fill", x + 3, y + 3, 7, 2)
  love.graphics.rectangle("fill", x + 12, y + 3, 7, 2)
  -- Eyes
  love.graphics.setColor(1, 0.88, 0.05)
  love.graphics.rectangle("fill", x + 3,  y + 5, 5, 5)
  love.graphics.rectangle("fill", x + 12, y + 5, 5, 5)
  -- Pupils (follow player direction)
  local pShift = g.dir > 0 and 1 or 0
  love.graphics.setColor(0, 0, 0)
  love.graphics.rectangle("fill", x + 3  + pShift, y + 6, 2, 3)
  love.graphics.rectangle("fill", x + 12 + pShift, y + 6, 2, 3)
  -- Smirk
  love.graphics.setColor(0.15, 0.04, 0.22)
  love.graphics.rectangle("fill", x + 6, y + 14, 10, 2)
  love.graphics.rectangle("fill", x + 6, y + 16, 2,  2)
  love.graphics.rectangle("fill", x + 14,y + 16, 2,  2)

  -- State labels
  if g.state == "EAT" then
    love.graphics.setColor(1, 1, 0.5)
    love.graphics.printf("NOM NOM!", x - 20, y - 14, g.w + 40, "center")
  elseif g.state == "STRUT" then
    love.graphics.setColor(0.2, 1, 0.5)
    love.graphics.printf(":)", x - 10, y - 12, g.w + 20, "center")
  end

  -- Name
  love.graphics.setColor(0.85, 0.35, 1)
  love.graphics.printf("GREGG", x - 20, y - 10, g.w + 40, "center")

  -- Blame text
  if g._blameText then
    love.graphics.setColor(1, 0.1, 0.1)
    love.graphics.printf(g._blameText, x - 70, y - 28, g.w + 140, "center")
  end
end

return CA
