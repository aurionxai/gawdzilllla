-- src/scenes/city_assault.lua
-- Side-scrolling kaiju rampage through a city.
-- Player scrolls left/right through a wide level, finds items, fights to the boss.

local SM      = require("src/scene_manager")
local Ctrl    = require("src/controller")
local Input   = require("src/input")
local AS      = require("src/attack_system")
local AM      = require("src/audio_manager")
local Pool    = require("src/blood_pool")
local NPC     = require("src/npc")
local CPU     = require("src/cpu_controller")
local FR      = require("src/food_renderer")
local SL      = require("src/story_lore")
local LM      = require("src/landmark_defs")
local CR      = require("src/city_renderer")
local KS      = require("src/kaiju_sprites")
local RD      = require("src/restaurant_defs")

local CA = {}
CA.__index = CA

local SCREEN_W  = 480
local SCREEN_H  = 270
local GROUND_Y  = 220
local LEVEL_W   = 4800    -- wide scrolling level
local CAM_LERP  = 5.0

-- Item types scattered through the level
local POWER_NAMES = { "GROUND SLAM", "DASH STRIKE", "SHIELD BURST", "RAGE MODE" }

-- Fart types: cycled on each F press
local FART_TYPES = {
  { name="SILENT BUT DEADLY",   color={0.35,0.75,0.25}, damage=8,  radius=50,  duration=2.0, count=6  },
  { name="FIRE IN THE HOLE!!",  color={1.00,0.38,0.05}, damage=22, radius=38,  duration=1.0, count=4  },
  { name="ARCTIC BLAST",        color={0.30,0.65,1.00}, damage=3,  radius=65,  duration=3.0, count=9,  slow=true },
  { name="MEGA FART — RUN!!",   color={0.88,0.22,0.95}, damage=30, radius=180, duration=1.8, count=14 },
}

local GREGG_BLAME = {
  "IT WAS %s!!",
  "NOT ME — %s DID IT!",
  "%s CROPDUSTED US ALL!",
  "DEFINITELY %s. I SAW IT.",
  "I SWEAR IT WASN'T ME, IT WAS %s!",
}

local GREGG_W, GREGG_H   = 22, 30
local GREGG_SPEED        = 55
local GREGG_FOOD_TRIGGER = 2   -- spawn after this many food items collected

local FOOD_POWERUP = {
  -- Speed surge (10 sec, 2x speed)
  energydrink="SPEED SURGE", coffee="SPEED SURGE", soda="SPEED SURGE",
  juice="SPEED SURGE", boba="SPEED SURGE",
  -- Damage boost (15 sec, 1.6x damage)
  steak="DAMAGE BOOST", lobster="DAMAGE BOOST", turkey="DAMAGE BOOST",
  wings="DAMAGE BOOST", corndog="DAMAGE BOOST", kebab="DAMAGE BOOST",
  -- Rage (fill power meter instantly)
  birthdaycake="RAGE MODE", ramen="RAGE MODE", curry="RAGE MODE",
  noodles="RAGE MODE", friedrice="RAGE MODE",
  -- Everything else defaults to HEAL (+30 HP)
}

-- Buildings and furniture are generated by CR (city_renderer)

local function genEnemies(rng)
  local enemies = {}
  -- Civilians visible immediately
  for i = 1, 8 do
    table.insert(enemies, { x = rng(100, 450), type="civilian", spawned=false })
  end
  -- Police near start (challenge from go)
  for i = 1, 5 do
    table.insert(enemies, { x = rng(220, 600), type="police", spawned=false })
  end
  -- Small monsters throughout (appear early and often)
  for i = 1, 16 do
    table.insert(enemies, { x = rng(250, LEVEL_W-300), type="monster", spawned=false })
  end
  -- Police: scattered mid-level
  for i = 1, 14 do
    table.insert(enemies, { x = rng(600, LEVEL_W-400), type="police", spawned=false })
  end
  -- More civilians fleeing mid-level
  for i = 1, 10 do
    table.insert(enemies, { x = rng(500, LEVEL_W-500), type="civilian", spawned=false })
  end
  -- Tanks: from mid-level
  for i = 1, 7 do
    table.insert(enemies, { x = rng(math.floor(LEVEL_W/2), LEVEL_W-600), type="tank", spawned=false })
  end
  table.sort(enemies, function(a,b) return a.x < b.x end)
  return enemies
end

local function genItems(rng, foodPool)
  local pool = foodPool or FR.TYPES
  local items = {}
  -- Food items (city-themed): scattered ? boxes
  for i = 1, 14 do
    local fx = rng(300, LEVEL_W - 300)
    local fy = GROUND_Y - 16 - rng(0,1)*rng(30,80)
    table.insert(items, {
      x=fx, y=fy, w=16, h=16,
      kind="food", type=pool[rng(1, #pool)],
      collected=false, pulse=rng(0,100)*0.01,
    })
  end
  -- Power unlocks
  for i = 1, 4 do
    local px = rng(600, LEVEL_W - 600)
    table.insert(items, {
      x=px, y=GROUND_Y - 90 - rng(0,60), w=18, h=18,
      kind="power", slot=i, name=POWER_NAMES[i],
      collected=false, pulse=rng(0,100)*0.01,
    })
  end
  -- Speed boost
  for i = 1, 3 do
    table.insert(items, {
      x=rng(400, LEVEL_W-400), y=GROUND_Y-16, w=14, h=14,
      kind="speed", collected=false, pulse=rng(0,100)*0.01,
    })
  end
  return items
end

-- ── Constructor ───────────────────────────────────────────────────────────────

function CA.new(playerCharInfo, bossCharInfo, citiesData, storyCityKey)
  local self = setmetatable({}, CA)

  self._storyCityKey = storyCityKey
  self._audio        = AM.getInstance()
  self._audio:playMusic()

  -- Seeded-ish RNG via closure
  local function rng(a, b) return math.random(a, b) end

  -- Player
  local PMod   = require(playerCharInfo.module)
  self._p1     = PMod.new()
  self._ctrl1  = Ctrl.new(self._p1.character, 80, GROUND_Y)
  self._ctrl1.character = self._p1.character
  self._ctrl1._levelW   = LEVEL_W
  self._maxHP  = self._p1.character.stats.maxHealth

  -- Camera
  self._camX      = 0
  self._levelW    = LEVEL_W

  -- Restaurant (one per city, special cinema power-up)
  self._restDef  = RD.get(storyCityKey)
  self._restX    = math.floor(LEVEL_W * 0.35)  -- at 35% through the level
  self._restUsed = false

  -- World objects (food items use city-specific pool)
  self._buildings = CR.generateBuildings(LEVEL_W, GROUND_Y)
  self._furniture = CR.generateFurniture(LEVEL_W, GROUND_Y)
  self._enemyDefs = genEnemies(rng)
  self._items     = genItems(rng, self._restDef.foods)
  self._npcs      = {}
  self._projectiles = {}

  -- Boss
  self._bossInfo  = bossCharInfo
  self._bossChar  = nil
  self._bossCtrl  = nil
  self._bossCPU   = nil
  self._bossSpawned = false

  -- Blood pool
  self._pool = Pool.new()

  -- City visuals (sky/ground colors from a random city def)
  local cd = citiesData[rng(1, #citiesData)]
  self._skyC  = cd.skyC  or {0.10, 0.14, 0.28}
  self._gndC  = cd.gndC  or {0.22, 0.20, 0.18}
  self._landmark = LM.get(storyCityKey)

  -- Player powers (ASDF)
  self._powers = { false, false, false, false }  -- unlocked by items
  self._powerTimers = { 0, 0, 0, 0 }

  -- Speed buff
  self._speedMult    = 1.0
  self._speedTimer   = 0

  self._damageMult  = 1.0
  self._damageTimer = 0

  -- Dollars / kills
  self._dollars   = 0
  self._killCount = 0

  -- State machine
  self._state     = "FIGHTING"  -- FIGHTING | BOSS | CHOICE | CINEMA | VICTORY | DEFEAT
  self._fadeAlpha = 1.0
  self._fadingIn  = true

  -- Choice
  self._choiceSel   = 1
  self._choiceMade  = false
  self._choicePulse = 0
  self._spared      = false

  -- Cinema scene
  self._cinema      = nil

  -- Announce banner
  self._announce     = nil
  self._announceTimer = 0

  -- Fart state
  self._fartTimer   = 0
  self._fartClouds  = {}
  self._fartTypeIdx = 0   -- cycles through FART_TYPES

  -- Gregg
  self._gregg         = nil
  self._foodCollected = 0

  -- Splat streak
  self._timeAccum  = 0
  self._killTimes  = {}

  -- Screen flash (unleash)
  self._screenFlash = 0

  return self
end

-- ── Camera ────────────────────────────────────────────────────────────────────

function CA:_updateCamera(dt)
  local target = self._ctrl1.x - SCREEN_W / 2
  target = math.max(0, math.min(LEVEL_W - SCREEN_W, target))
  self._camX = self._camX + (target - self._camX) * math.min(1, CAM_LERP * dt)
end

-- ── Enemy spawning (activate when camera reveals them) ────────────────────────

function CA:_activateEnemies()
  local visR = self._camX + SCREEN_W + 120  -- slightly ahead of visible
  for _, def in ipairs(self._enemyDefs) do
    if not def.spawned and def.x < visR then
      def.spawned = true
      local npc = NPC.new(def.x, GROUND_Y, def.type,
        def.type == "tank" and 15000 or 2000)
      table.insert(self._npcs, npc)
    end
  end
end

-- Boss spawns when player reaches 85% through the level
function CA:_checkBossSpawn()
  if not self._bossSpawned and self._ctrl1.x > LEVEL_W * 0.85 then
    self._bossSpawned = true
    local BMod      = require(self._bossInfo.module)
    self._bossChar  = BMod.new()
    self._bossCtrl  = Ctrl.new(self._bossChar.character, LEVEL_W - 160, GROUND_Y)
    self._bossCtrl.facingRight  = false
    self._bossCtrl.character    = self._bossChar.character
    self._bossCtrl._levelW      = LEVEL_W
    self._bossCPU   = CPU.new()
    self._state     = "BOSS"
    self._announce     = "⚠  " .. self._bossInfo.name .. "  APPEARS!"
    self._announceTimer = 2.8
  end
end

-- ── Update ────────────────────────────────────────────────────────────────────

function CA:update(dt)
  -- Fade in
  if self._fadingIn then
    self._fadeAlpha = math.max(0, self._fadeAlpha - dt * 2.5)
    if self._fadeAlpha <= 0 then self._fadingIn = false end
  end

  if self._announceTimer > 0 then self._announceTimer = self._announceTimer - dt end

  if self._state == "VICTORY" or self._state == "DEFEAT" then
    self._fadeAlpha = math.min(1, self._fadeAlpha + dt * 1.5)
    if self._fadeAlpha >= 1 then
      local SS = require("src/story_state")
      local WM = require("src/scenes/world_map")
      if self._state == "VICTORY" and self._storyCityKey then
        SS.conquer(self._storyCityKey)
      end
      SM.replace(WM.new({ won=(self._state=="VICTORY"), cityKey=self._storyCityKey }))
    end
    return
  end

  if self._state == "CINEMA" then
    self:_updateCinema(dt)
    return
  end

  -- Player move
  local moveX = (self._p1.character.isDefeated) and 0 or Input.getMoveX(1)
  local spd   = self._speedMult
  if self._speedTimer > 0 then
    self._speedTimer = self._speedTimer - dt
    if self._speedTimer <= 0 then self._speedMult = 1.0 end
  end
  if self._damageTimer > 0 then
    self._damageTimer = self._damageTimer - dt
    if self._damageTimer <= 0 then self._damageMult = 1.0 end
  end
  -- Temporarily patch moveSpeed for speed buff
  local baseSpd = self._p1.character.stats.moveSpeed
  if spd ~= 1.0 then self._p1.character.stats.moveSpeed = baseSpd * spd end

  self._ctrl1:update(dt, moveX, self._buildings)
  self._p1:update(dt)
  self._p1.attacks:update(dt, self._ctrl1.x, self._ctrl1.facingRight)

  if spd ~= 1.0 then self._p1.character.stats.moveSpeed = baseSpd end

  -- Player death
  if self._p1.character.isDefeated then
    self._state     = "DEFEAT"
    self._fadeAlpha = 0
    return
  end

  self:_updateCamera(dt)
  self:_activateEnemies()
  self._pool:update(dt)

  -- Fart clouds
  self._fartTimer = math.max(0, self._fartTimer - dt)
  for i = #self._fartClouds, 1, -1 do
    local fc = self._fartClouds[i]
    fc.timer = fc.timer - dt
    fc.x = fc.x + fc.vx * dt
    if fc.timer <= 0 then table.remove(self._fartClouds, i) end
  end

  -- Time accumulator for streak window
  self._timeAccum = self._timeAccum + dt
  local cutoff = self._timeAccum - 2.0
  for i = #self._killTimes, 1, -1 do
    if self._killTimes[i] < cutoff then table.remove(self._killTimes, i) end
  end
  self._screenFlash = math.max(0, self._screenFlash - dt * 2.5)

  -- Gregg
  if self._gregg then self:_updateGregg(dt) end

  -- Item collection
  self:_checkItems()

  -- Restaurant trigger (one-time, at ~35% of level)
  if not self._restUsed and self._ctrl1.x > self._restX then
    self._restUsed = true
    self:_startRestaurantCinema()
  end

  if self._state == "CHOICE" then
    self._choicePulse = self._choicePulse + dt * 3
    self._bossCtrl:update(dt, 0, self._buildings)
    return
  end

  if self._state == "FIGHTING" then
    self:_updateFighting(dt)
    self:_checkBossSpawn()
  elseif self._state == "BOSS" then
    self:_updateBoss(dt)
  end
end

function CA:_updateFighting(dt)
  -- Player bounds (used throughout)
  local cb = self._ctrl1:getBounds()

  -- Building contact damage: walking through buildings smashes them
  if math.abs(self._ctrl1.vx) > 25 then
    for _, b in ipairs(self._buildings) do
      if not b.isDestroyed then
        local bb = { x=b.x, y=b.y, w=b.w, h=b.h }
        if AS.overlaps(cb, bb) then
          local dmg = math.abs(self._ctrl1.vx) * dt * 0.12 * self._damageMult
          b.health = b.health - dmg
          if b.health <= 0 then
            b.isDestroyed = true
            self._dollars   = self._dollars + b.dollarsValue
            self._killCount = self._killCount + 1
            self._pool:spawn(b.x + b.w/2, GROUND_Y)
            self._audio:playCollapse()
          end
        end
      end
    end
  end

  -- Player attacks on buildings (Z key swing hitboxes)
  local boxes = self._p1.attacks:getHitboxes(self._ctrl1.x, self._ctrl1.y, self._ctrl1.facingRight)
  for _, b in ipairs(self._buildings) do
    if not b.isDestroyed then
      local bb = { x=b.x, y=b.y, w=b.w, h=b.h }
      for _, hb in ipairs(boxes) do
        if AS.overlaps(hb, bb) then
          b.health = b.health - (hb.damage or 1) * self._damageMult
          if b.health <= 0 then
            b.isDestroyed = true
            self._dollars   = self._dollars + b.dollarsValue
            self._killCount = self._killCount + 1
            self._pool:spawn(b.x + b.w/2, GROUND_Y)
            self._audio:playCollapse()
          end
          self._p1.character:gainPower(hb.powerGain or 0)
          self._audio:playHit(hb.damage or 1)
          break
        end
      end
    end
  end

  -- NPC updates + projectile firing
  local p1targets = {{ x=self._ctrl1.x, y=self._ctrl1.y }}
  for _, npc in ipairs(self._npcs) do
    local result, dir = npc:update(dt, p1targets)
    if result == "police_shot" or result == "tank_shot" then
      local spd = npc.npcType == "tank" and 220 or 140
      local dmg = npc.npcType == "tank" and 10  or 2
      table.insert(self._projectiles, {
        x=npc.x, y=npc.y - npc.height/2,
        vx=dir*spd, damage=dmg, type=npc.npcType,
        w=6, h=3, _alive=true
      })
    elseif result == "monster_bite" then
      self._p1.character:takeDamage(5)
      self._audio:playHit(5)
    end
  end

  -- Projectile movement + player hit
  for _, p in ipairs(self._projectiles) do
    if p._alive then
      p.x = p.x + p.vx * dt
      if p.x < self._camX - 60 or p.x > self._camX + SCREEN_W + 60 then
        p._alive = false
      end
      local cb = self._ctrl1:getBounds()
      if p.x < cb.x+cb.w and p.x+p.w > cb.x and p.y < cb.y+cb.h and p.y+p.h > cb.y then
        p._alive = false
        self._p1.character:takeDamage(p.damage)
        self._audio:playHit(p.damage)
      end
    end
  end

  -- Player attacks on NPCs
  for _, npc in ipairs(self._npcs) do
    if not npc.isDead then
      local nb = { x=npc.x - npc.width/2, y=npc.y - npc.height, w=npc.width, h=npc.height }
      for _, hb in ipairs(boxes) do
        if AS.overlaps(hb, nb) then
          npc.health = (npc.health or 1) - self._damageMult
          if npc.health <= 0 then
            npc.isDead = true
            self._dollars   = self._dollars + (npc.dollarsValue or 1000)
            self._killCount = self._killCount + 1
            self._pool:spawn(npc.x, GROUND_Y)
            self._audio:playRandomSplat()
            self:_registerKill()
          else
            npc._hitFlash = 0.12
          end
          self._p1.character:gainPower(hb.powerGain or 0)
          self._audio:playHit(hb.damage or 1)
          break
        end
      end
    end
  end

  -- Fart cloud damages nearby NPCs (properties per cloud type)
  for _, fc in ipairs(self._fartClouds) do
    local rad = fc.radius or 50
    local dmg = fc.damage or 8
    for _, npc in ipairs(self._npcs) do
      if not npc.isDead and math.abs(npc.x - fc.x) < rad then
        npc.health = (npc.health or 1) - dt * dmg
        if fc.slow then
          npc.vx = npc.vx * math.max(0, 1 - dt * 4)
        end
        if npc.health <= 0 then
          npc.isDead = true
          self._pool:spawn(npc.x, GROUND_Y)
          self._audio:playRandomSplat()
          self:_registerKill()
        end
      end
    end
  end

  -- Stomp
  local stp = { x=cb.x, y=cb.y+cb.h-8, w=cb.w, h=8 }
  for _, npc in ipairs(self._npcs) do
    if not npc.isDead then
      local nb = { x=npc.x-npc.width/2, y=npc.y-npc.height, w=npc.width, h=npc.height }
      if AS.overlaps(stp, nb) then
        npc.isDead = true
        self._pool:spawn(npc.x, GROUND_Y)
        self._audio:playRandomSplat()
        self:_registerKill()
      end
    end
  end

  -- Clean dead
  for i = #self._npcs,        1, -1 do if self._npcs[i].isDead         then table.remove(self._npcs, i)        end end
  for i = #self._projectiles, 1, -1 do if not self._projectiles[i]._alive then table.remove(self._projectiles, i) end end
end

function CA:_updateBoss(dt)
  local bChar  = self._bossChar.character
  local bMaxHP = bChar.stats.maxHealth

  -- Mercy threshold
  if not self._choiceMade and not bChar.isDefeated then
    if bChar.health <= bMaxHP * 0.20 then
      self._state       = "CHOICE"
      self._choicePulse = 0
      return
    end
  end

  -- Boss AI
  if not bChar.isDefeated then
    local bmx = self._bossCPU:think(dt, self._bossCtrl, self._ctrl1)
    self._bossCtrl:update(dt, bmx, self._buildings)
    self._bossChar:update(dt)
    self._bossChar.attacks:update(dt, self._bossCtrl.x, self._bossCtrl.facingRight)
    if self._bossCPU._doJump    then self._bossCtrl:jump() end
    if self._bossCPU._doAttack  then self._bossChar.attacks:performLight() end
    if self._bossCPU._doSpecial then self._bossChar.attacks:performSpecial() end
  end

  -- Mutual hits
  self:_checkHits(self._p1.attacks, self._ctrl1, bChar, self._bossCtrl)
  self:_checkHits(self._bossChar.attacks, self._bossCtrl, self._p1.character, self._ctrl1)

  -- Still run fighting logic (NPCs still active)
  self:_updateFighting(dt)

  if bChar.isDefeated then
    local lore = SL.get(self._storyCityKey)
    self._state       = "VICTORY"
    self._announce    = self._spared and lore.spare_text or lore.destroy_text
    self._announceTimer = 4.0
    self._fadeAlpha   = 0
  end
end

function CA:_checkHits(atk, atkCtrl, targetChar, targetCtrl)
  if targetChar.isDefeated then return end
  local boxes = atk:getHitboxes(atkCtrl.x, atkCtrl.y, atkCtrl.facingRight)
  local tb    = targetCtrl:getBounds()
  for _, hb in ipairs(boxes) do
    if AS.overlaps(hb, tb) then
      targetChar:takeDamage(hb.damage)
      atk.character:gainPower(hb.powerGain or 0)
      if hb.stunDuration and hb.stunDuration > 0 then
        targetCtrl:applyStun(hb.stunDuration)
      end
      local dir = atkCtrl.facingRight and 1 or -1
      targetCtrl:applyKnockback(dir * hb.damage * 4, -hb.damage * 2)
      self._audio:playHit(hb.damage)
    end
  end
end

-- ── Item collection ───────────────────────────────────────────────────────────

function CA:_checkItems()
  local cb = self._ctrl1:getBounds()
  for _, item in ipairs(self._items) do
    if not item.collected then
      local ib = { x=item.x, y=item.y, w=item.w, h=item.h }
      if AS.overlaps(cb, ib) then
        item.collected = true
        if item.kind == "food" then
          self._foodCollected = self._foodCollected + 1
          if self._foodCollected == GREGG_FOOD_TRIGGER and not self._gregg then
            self:_spawnGregg()
          end
          self:_startCinema(item)
        elseif item.kind == "power" then
          self._powers[item.slot] = true
          self._announce     = item.name .. " UNLOCKED!"
          self._announceTimer = 2.5
          self._audio:playCollapse()
        elseif item.kind == "speed" then
          self._speedMult  = 1.8
          self._speedTimer = 8.0
          self._announce     = "SPEED BOOST!"
          self._announceTimer = 1.8
        end
      end
    end
  end
end

-- ── Cinema scene (food found) ─────────────────────────────────────────────────

function CA:_startCinema(item)
  local effect = FOOD_POWERUP[item.type] or "HEAL"
  self._cinema = {
    item    = item,
    phase   = "in",
    alpha   = 0,
    hold    = 0.9,   -- short hold; any key skips immediately
    pulse   = 0,
    effect  = effect,
  }
  self._prevState = self._state
  self._state     = "CINEMA"
end

function CA:_startRestaurantCinema()
  local rd = self._restDef
  self._cinema = {
    kind    = "restaurant",
    phase   = "in",
    alpha   = 0,
    hold    = 2.5,
    pulse   = 0,
    effect  = rd.effect,
    -- restaurant-specific display fields
    restName  = rd.name,
    restSub   = rd.sub,
    welcome   = rd.welcome,
    signCol   = rd.signCol,
    food      = rd.food,
    foodLabel = rd.foodLabel,
  }
  self._prevState = self._state
  self._state     = "CINEMA"
end

function CA:_applyEffect(effect)
  if effect == "SPEED SURGE" then
    self._speedMult  = 2.0
    self._speedTimer = 10.0
  elseif effect == "DAMAGE BOOST" then
    self._damageMult  = 1.6
    self._damageTimer = 15.0
  elseif effect == "RAGE MODE" then
    self._p1.character.power = 100
    if self._p1.character.onPowerChanged then
      self._p1.character.onPowerChanged(100)
    end
  else  -- HEAL
    self._p1.character:heal(30)
  end
end

function CA:_updateCinema(dt)
  local c = self._cinema
  c.pulse = c.pulse + dt * 4
  if c.phase == "in" then
    c.alpha = math.min(1, c.alpha + dt * 3.5)
    if c.alpha >= 1 then
      c.phase = "hold"
      self:_applyEffect(c.effect)
    end
  elseif c.phase == "hold" then
    c.hold = c.hold - dt
    if c.hold <= 0 then c.phase = "out" end
  elseif c.phase == "out" then
    c.alpha = math.max(0, c.alpha - dt * 3.5)
    if c.alpha <= 0 then
      self._state  = self._prevState
      self._cinema = nil
    end
  end
end

-- ── Fart attack ───────────────────────────────────────────────────────────────

function CA:_doFart()
  if self._fartTimer > 0 then return end
  -- Cycle to next fart type
  self._fartTypeIdx = (self._fartTypeIdx % #FART_TYPES) + 1
  local ft  = FART_TYPES[self._fartTypeIdx]
  self._fartTimer = 3.0
  local dir = self._ctrl1.facingRight and -1 or 1
  for i = 1, ft.count do
    local spread = (i - 1) / math.max(ft.count - 1, 1)
    table.insert(self._fartClouds, {
      x        = self._ctrl1.x + dir * (8 + i * math.floor(ft.radius / ft.count)),
      y        = GROUND_Y - math.random(8, 55),
      vx       = dir * math.random(18, 65),
      timer    = ft.duration * (0.7 + math.random() * 0.6),
      maxTimer = ft.duration,
      color    = ft.color,
      damage   = ft.damage,
      radius   = ft.radius,
      slow     = ft.slow,
    })
  end
  self._announce     = ft.name
  self._announceTimer = 2.0
end

-- ── Splat streak tracker ──────────────────────────────────────────────────────

function CA:_registerKill()
  table.insert(self._killTimes, self._timeAccum)
