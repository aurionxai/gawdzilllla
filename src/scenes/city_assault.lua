    self._announceTimer = 2.2
  end
end

-- ── Power moves ───────────────────────────────────────────────────────────────

function CA:_doSpecial(slot)
  if not self._powers[slot] and slot > 1 then
    self._announce     = "??? — FIND THE POWER ITEM!"
    self._announceTimer = 1.5
    return
  end
  if slot == 1 then
    -- A: character special
    self._p1.attacks:performSpecial()
  elseif slot == 2 then
    -- S: ground slam — damage all NPCs on screen
    for _, npc in ipairs(self._npcs) do
      if not npc.isDead and
         npc.x > self._camX - 20 and npc.x < self._camX + SCREEN_W + 20 then
        npc.health = (npc.health or 1) - 3
        if npc.health <= 0 then npc.isDead = true; self._pool:spawn(npc.x, GROUND_Y) end
      end
    end
    self._announce     = "GROUND SLAM!"
    self._announceTimer = 1.2
    self._audio:playCollapse()
  elseif slot == 3 then
    -- D: dash strike
    local dir = self._ctrl1.facingRight and 1 or -1
    self._ctrl1._knockbackVX = dir * 400
    self._announce     = "DASH STRIKE!"
    self._announceTimer = 1.0
  elseif slot == 4 then
    -- F key used for fart, but slot 4 = RAGE
    self._speedMult  = 2.2
    self._speedTimer = 6.0
    self._p1.character:heal(15)
    self._announce     = "RAGE MODE!"
    self._announceTimer = 1.5
  end
end

-- ── Input ─────────────────────────────────────────────────────────────────────

function CA:keypressed(key)
  if self._state == "CINEMA" then
    -- any key skips immediately once hold has started
    if self._cinema and self._cinema.phase == "hold" then
      self._cinema.phase = "out"
    end
    return
  end

  if self._state == "CHOICE" then
    if key == "left"  then self._choiceSel = 1 end
    if key == "right" then self._choiceSel = 2 end
    if key == "return" or key == "space" then
      self._choiceMade = true
      self._spared     = (self._choiceSel == 2)
      self._bossChar.character.isDefeated = true
      local lore = SL.get(self._storyCityKey)
      self._state     = "VICTORY"
      self._announce  = self._spared and lore.spare_text or lore.destroy_text
      self._announceTimer = 4.0
      self._fadeAlpha = 0
    end
    return
  end

  local a = Input.getAction(1, key)
  if a == "jump"     then self._ctrl1:jump() end
  if a == "attack"   then self._p1.attacks:performLight() end
  if a == "heavy"    then self._p1.attacks:performHeavy() end
  if a == "unleash"  then
    if self._p1.character:isPowerFull() then
      if self._p1.triggerUnleash then self._p1:triggerUnleash() else self._p1.attacks:performUnleash() end
      self._screenFlash   = 1.0
      self._announce      = (self._p1.stats.characterName or "KAIJU"):upper() .. " UNLEASHES!!"
      self._announceTimer = 2.5
    else
      self._announce      = "POWER METER NOT FULL — CHARGE UP!"
      self._announceTimer = 1.2
    end
  end
  if a == "special"  then self:_doSpecial(1) end
  if a == "super"    then self:_doSpecial(2) end
  if a == "special2" then self:_doSpecial(3) end
  if a == "fart"     then self:_doFart() end

  if key == "escape" then
    local MM = require("src/scenes/main_menu")
    SM.replace(MM.new())
  end
end

